// FuzzParseISO8601 holds this package's parse_iso8601, on the C string
// ParseHTTPTime gives it, to iso8601.ParseExtended, which is to replace it.
func FuzzParseISO8601(f *testing.F) {
	for _, s := range isoSeeds {
		f.Add(s)
	}
	f.Fuzz(func(t *testing.T, s string) {
		wantTm, wantNS, wantOK := parseISO8601(rgwtext.CString(s))
		gotTm, gotNS, gotOK := iso8601.ParseExtended(s)
		if gotTm != wantTm || gotNS != wantNS || gotOK != wantOK {
			t.Fatalf("%q: ParseExtended gives %+v, %d, %t; parseISO8601 %+v, %d, %t", s, gotTm, gotNS, gotOK, wantTm, wantNS, wantOK)
		}
	})
}
